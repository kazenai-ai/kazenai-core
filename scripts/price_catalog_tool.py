#!/usr/bin/env python3
"""Operator tool for the signed KazenAI price catalog.

    keygen  --out-dir DIR [--kid KID]       new Ed25519 pricing key pair (private key 0600)
    export  --out FILE [--version V] [--days N]   bundled catalog as an unsigned payload
    sign    --in FILE --key PEM --kid KID --out FILE   sign a reviewed payload
    verify  --in FILE [--public-key KID=B64URL]        verify a signed catalog

The private key never goes into a repository, CI secret, or service. Keep it
offline (or in a KMS that signs the canonical payload bytes) and pin only the
public key in ``kazenai/catalog_document.py`` ``TRUSTED_CATALOG_KEYS``.
Nothing here prints a private key.
"""

from __future__ import annotations

import argparse
import base64
import json
import os
import sys
from datetime import timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from kazenai import catalog_document as cd  # noqa: E402


def _keygen(args: argparse.Namespace) -> int:
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    os.chmod(out, 0o700)
    private_path = out / f"{args.kid}.private.pem"
    if private_path.exists():
        print(f"refusing to overwrite {private_path}", file=sys.stderr)
        return 2
    key = Ed25519PrivateKey.generate()
    pem = key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption())
    fd = os.open(private_path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "wb") as handle:
        handle.write(pem)
    raw = key.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    public = base64.urlsafe_b64encode(raw).rstrip(b"=").decode()
    print(f"private key written to {private_path} (mode 0600). Move it offline.")
    print("pin this public key in kazenai/catalog_document.py TRUSTED_CATALOG_KEYS:")
    print(f'    "{args.kid}": "{public}",')
    return 0


def _export(args: argparse.Namespace) -> int:
    payload = cd.export_payload(version=args.version, expires_in=timedelta(days=int(args.days)))
    Path(args.out).write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"wrote catalog {payload['catalog_version']} ({len(payload['rows'])} rows) to {args.out}; review it, then sign")
    return 0


def _sign(args: argparse.Namespace) -> int:
    payload = json.loads(Path(args.input).read_text(encoding="utf-8"))
    envelope = cd.sign_payload(payload, private_key_pem=Path(args.key).read_bytes(), kid=args.kid)
    Path(args.out).write_text(json.dumps(envelope, separators=(",", ":")) + "\n", encoding="utf-8")
    print(f"signed catalog {payload['catalog_version']} with {args.kid} -> {args.out}")
    return 0


def _verify(args: argparse.Namespace) -> int:
    keys = None
    if args.public_key:
        keys = {}
        for item in args.public_key:
            kid, _, value = item.partition("=")
            keys[kid] = base64.urlsafe_b64decode(value + "=" * (-len(value) % 4))
    raw = Path(args.input).read_bytes()
    payload, kid, digest = cd.verify_envelope(raw, keys=keys)
    bundle = cd.parse_payload(payload, sha256=digest)
    print(
        f"ok: catalog {bundle.version}, {len(bundle.rows)} rows, key {kid}, "
        f"issued {bundle.issued_at}, expires {bundle.expires_at}, sha256 {digest}"
    )
    return 0


def _render_doc() -> str:
    from kazenai import price_catalog as pc

    b = pc.BUNDLED
    out: list[str] = []
    w = out.append
    w("# Price catalog\n")
    w(f"Catalog version `{b.version}`. Verification date `{pc.VERIFIED_ON}`. Generated by `scripts/price_catalog_tool.py doc`; edit `kazenai/price_catalog.py`, not this file.")
    w(f"Rounding rule `{pc.ROUNDING_RULE}`: half-even to nanos, then ceiling to integer micro-USD.")
    w("This snapshot ships in the `kazenai` package and is the default and the floor. A newer catalog signed with a pinned KazenAI pricing key, distributed by Agent FinOps, replaces it while unexpired (see \"Signed live catalog\").\n")
    w("Lookup is the exact canonical id, then the explicit alias table. There is no prefix inheritance.")
    w("`-latest` and a dated snapshot that is not in the alias table are unknown and block by default.\n")
    w("## Sources\n")
    for name, url in (("openai", pc.OPENAI_SOURCE), ("anthropic", pc.ANTHROPIC_SOURCE), ("google", pc.GOOGLE_SOURCE), ("deepseek", pc.DEEPSEEK_SOURCE),
                      ("OpenAI image formula and sizing", pc.OPENAI_VISION_SOURCE), ("Anthropic image formula", pc.ANTHROPIC_VISION_SOURCE),
                      ("Anthropic client tools and tool overhead", pc.ANTHROPIC_TOOLS_SOURCE),
                      ("Anthropic fast mode", "https://platform.claude.com/docs/en/build-with-claude/fast-mode"),
                      ("OpenAI data residency domains", "https://developers.openai.com/api/docs/guides/your-data")):
        w(f"- {name}: {url} (checked {pc.VERIFIED_ON})")
    w("\n## SDK literals\n")
    w("Read from the locally installed packages. No network call was used to discover a type literal.\n")
    w("- openai 1.109.1 request `service_tier`: `auto`, `default`, `flex`, `scale`, `priority`. Unset requests are pinned to `default`.")
    w("- anthropic 0.125.0 request `service_tier`: `auto`, `standard_only`. Unset requests are pinned to `standard_only`.")
    w("- anthropic usage `service_tier`: `standard`, `priority`, `batch`. Request `standard_only` reporting `standard` is the expected mapping.")
    w("- anthropic 0.125.0 accepts `inference_geo` but has no `speed` argument; fast mode is sent as `extra_body={\"speed\": \"fast\"}`.")
    w("- openai 1.109.1 has no `responses.input_tokens.count`. A model with a long-context band refuses on that client.")
    w("- OpenAI 2.x exact counting is `responses.input_tokens.count`. Anthropic counting is `messages.count_tokens`.\n")
    w("## Request rules\n")
    w("Every rule is applied to the request as sent: `extra_body` fields count exactly like top-level ones.\n")
    w(f"- Anthropic `speed`: allowed {', '.join(f'`{x}`' for x in b.anthropic_allowed_speeds)}. Fast mode (`speed: \"fast\"`, $8/$40 on Opus 5.5, $10/$50 on Opus 5 and 4.8) is refused before dispatch until a catalog certifies its rate card.")
    geo = ", ".join(f"`{k}` x{v}" for k, v in sorted(b.anthropic_inference_geo_multipliers.items()))
    w(f"- Anthropic `inference_geo`: {geo} (1.1x on every token category for Claude 4.6 and later, applied to every model as a ceiling). Other values are refused.")
    hosts = "; ".join(f"{k}: {', '.join(v)}" for k, v in sorted(b.first_party_api_hosts.items()))
    w(f"- Endpoints: first-party hosts ({hosts}) bill at list. Any other host (OpenAI data-residency `<cc>.api.openai.com`, FedRAMP, Azure, Bedrock, Vertex, a proxy) is priced at x{b.non_first_party_uplift}. An operator may declare an exact host list-priced with `KAZENAI_ENDPOINT_PRICE_MULTIPLIERS='{{\"llm-proxy.internal\": \"1\"}}'`; values below 1, wildcards, and paths are refused.")
    w("- A reported tier other than the pin is settled on that tier's certified row times the same request multiplier, or held under the operator risk multiplier.\n")
    w("## Anthropic tool overhead\n")
    w("With any `tools`, the API adds a tool-use system prompt and some client tools add definition tokens. The local estimate adds them; an exact counter already includes them. \"About\" figures carry a 10% margin.\n")
    w("| Model | tool_choice auto/none | tool_choice any/tool |")
    w("| --- | --- | --- |")
    for model, (a, t) in sorted(b.anthropic_tool_system_prompt_tokens.items()):
        w(f"| `{model}` | {a} | {t} |")
    w(f"\nA model not listed gets {b.anthropic_tool_system_prompt_fallback}.\n")
    w("| Client tool | Added input tokens |")
    w("| --- | --- |")
    for tool, tokens in sorted(b.anthropic_tool_definition_tokens.items()):
        w(f"| `{tool}` | {tokens} |")
    w("\n## Client tools\n")
    w("Anthropic client-tool version strings allowed under Control (anything else, and web search, web fetch, code execution, MCP servers, and containers, is refused):\n")
    for tool in b.anthropic_client_tool_versions:
        w(f"- `{tool}`")
    w("\n## Images\n")
    w("Inline images without an exact whole-request counter use the formulas on the vision pages. `detail=auto` (the default) and any unlisted detail use the most expensive detail the model supports. URL images and `file_id` are refused without an exact counter. Pillow (`kazenai[images]`) reads metadata only; a missing Pillow refuses the inline image. `observe_unbounded=(\"images\",)` records `spend_bound: none` and reserves text only. Files and documents by reference stay refused.\n")
    w("OpenAI tile models (base, tile tokens): " + ", ".join(f"`{m}` {bt[0]}/{bt[1]}" for m, bt in sorted(b.openai_tile_models.items())) + ".\n")
    w("| OpenAI patch model | Multiplier | low (edge, budget) | high | original |")
    w("| --- | --- | --- | --- | --- |")
    for model, mult in sorted(b.openai_patch_multipliers.items()):
        sizing = b.openai_patch_sizing.get(model)
        def cell(d):
            if sizing is None:
                return "largest allowance"
            v = sizing.get(d)
            return "not supported" if v is None else f"{v[0]} px, {v[1] or 'none'}"
        w(f"| `{model}` | {mult} | {cell('low')} | {cell('high')} | {cell('original')} |")
    w("\nAnthropic: `ceil(width/28) x ceil(height/28)` visual tokens, capped at 1568 px / 1568 tokens (4784 tokens at 2576 px on Claude 4.7 and later).\n")
    w("## Dated prices\n")
    for row in sorted(b.rows.values(), key=lambda r: r.key):
        for when, rates in row.scheduled:
            w(f"- `{row.model}` ({row.provider}, {row.context_band}): from {when} input {rates.input}, cached {rates.cached_input}, output {rates.output} per MTok.")
        if row.valid_until:
            w(f"- `{row.model}` ({row.provider}, {row.context_band}): promotional price valid until {row.valid_until}; afterwards uncertified (refused under Control) until a newer catalog confirms it.")
    w("\n## Aliases\n")
    w("Exact ids only. No prefixes, globs, or provider stripping.\n")
    for presented, canonical in sorted(b.aliases.items()):
        w(f"- `{presented}` -> `{canonical}`")
    w(f"\n## Certified rows ({sum(1 for r in b.rows.values() if r.certified)})\n")
    w("USD per 1M tokens. A blank component bills at the uncached input rate. Audio columns apply to audio input tokens where the provider prices them apart from text.\n")
    w("| Provider | Model | Request tier | Context band | Expected reported tier | Input | Cached input | Cache write 5m | Cache write 1h | Output | Audio input | Audio cached | Image | Tool/call | Long-context threshold | Source | Verified |")
    w("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    for row in sorted(b.rows.values(), key=lambda r: (r.provider != "openai", r.provider, r.key)):
        v = row.rates

        def f(x):
            return "" if x is None else format(x, "f")

        w(f"| {row.provider} | `{row.model}` | {row.request_tier} | {row.context_band} | {row.expected_reported_tier} | {f(v.input)} | {f(v.cached_input)} | {f(v.cache_write_5m)} | {f(v.cache_write_1h)} | {f(v.output)} | {f(v.audio_input)} | {f(v.audio_cached_input)} | {f(v.image)} | {f(v.tool_per_call)} | {row.long_context_threshold or ''} | {row.source_url} | {row.verified_on} |")
    uncertified = [r for r in b.rows.values() if not r.certified]
    w(f"\n## Uncertified rows ({len(uncertified)})\n")
    w(f"Each shipped row was matched to the linked provider page on {pc.VERIFIED_ON}. A row that cannot be matched to a fetched page must stay uncertified and is refused under Control. An operator override is labelled `operator_override`.\n")
    w("## Signed live catalog\n")
    w("- Format: `kazenai.price-catalog.v1` payload inside a `kazenai.price-catalog.signed.v1` envelope. The payload string is the exact canonical JSON that was signed (Ed25519, base64url).")
    w("- Keys: public keys are pinned in `kazenai/catalog_document.py` `TRUSTED_CATALOG_KEYS`; the private key stays offline. `KAZENAI_PRICING_CATALOG_PUBLIC_KEYS` can add (never replace) keys for self-hosted deployments.")
    w("- Refused: unsigned or tampered files, unknown keys, other algorithms, non-canonical payloads, versions older than the bundled snapshot or than any catalog already accepted (no rollback), expired catalogs, and catalogs issued in the future.")
    w("- Distribution: KazenAI publishes the signed catalog to a CDN; Agent FinOps fetches and stores it (`KAZENAI_PRICING_CATALOG_URL`) and serves it to SDK keys at `GET /v1/pricing/catalog`. SDKs connected to FinOps verify it themselves and cache it (`KAZENAI_PRICING_LIVE=0` turns this off). An SDK without FinOps uses the bundled snapshot.")
    w("- Authority: FinOps prices every reservation and settlement from its own catalog and keeps the higher of its figure and the SDK's, so a stale SDK cannot under-charge and an SDK on another catalog version is not refused.\n")
    w("## What the reserve decision carries\n")
    w("The decision freezes catalog version, presented and canonical ids, request tier, context band, rate vector (with any request multiplier folded in), rounding rule, and pricing source. Settlement uses that frozen vector. Settle bodies send the priced token components (`usage_evidence.tokens`) so FinOps can re-price them on the reservation's frozen card.")
    return "\n".join(out) + "\n"


def _doc(args: argparse.Namespace) -> int:
    Path(args.out).write_text(_render_doc(), encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("keygen")
    p.add_argument("--out-dir", required=True)
    p.add_argument("--kid", default="kzprice-1")
    p.set_defaults(func=_keygen)
    p = sub.add_parser("export")
    p.add_argument("--out", required=True)
    p.add_argument("--version", default=None, help="YYYY-MM-DD or YYYY-MM-DD.N; must be newer than any published catalog")
    p.add_argument("--days", default="30", help="validity in days (expires_at)")
    p.set_defaults(func=_export)
    p = sub.add_parser("sign")
    p.add_argument("--in", dest="input", required=True)
    p.add_argument("--key", required=True)
    p.add_argument("--kid", required=True)
    p.add_argument("--out", required=True)
    p.set_defaults(func=_sign)
    p = sub.add_parser("doc")
    p.add_argument("--out", required=True)
    p.set_defaults(func=_doc)
    p = sub.add_parser("verify")
    p.add_argument("--in", dest="input", required=True)
    p.add_argument("--public-key", action="append", help="KID=BASE64URL (default: pinned + env keys)")
    p.set_defaults(func=_verify)
    args = parser.parse_args(argv)
    try:
        return int(args.func(args))
    except cd.CatalogDocumentError as exc:
        print(f"refused: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
