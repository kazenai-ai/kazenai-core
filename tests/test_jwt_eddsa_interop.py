"""0.2 — tokens signed by Platform's TypeScript signer verify in Python.

The fixture is generated by kazenai-platform/scripts/gen-eddsa-interop-fixture.ts.
The canonical bytes ship in the kazenai-contracts wheel; this is a vendored copy.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from kazenai.auth.jwt import JwtVerifyError, platform_token_profile, verify_eddsa_token

FIXTURE = Path(__file__).with_name("fixtures") / "eddsa_interop.v1.json"
DATA = json.loads(FIXTURE.read_text(encoding="utf-8"))


def test_copy_matches_the_contracts_corpus():
    # The private contracts wheel is absent in this public repo's standalone CI.
    resources = pytest.importorskip("kazenai_contracts.resources")
    assert resources.auth_fixture_json("eddsa_interop.v1.json") == DATA


@pytest.mark.parametrize("case", DATA["cases"], ids=[c["name"] for c in DATA["cases"]])
def test_platform_signed_tokens_verify_in_python(case, monkeypatch):
    monkeypatch.setenv("KAZENAI_PLATFORM_JWT_ISSUER", DATA["issuer"])
    profile = platform_token_profile(
        audience=case["audience"],
        token_use=case["token_use"],
        max_ttl_seconds=case["max_ttl"],
        public_keys=tuple(DATA["public_keys"].items()),
    )
    now = int(case.get("verify_at", DATA["verify_at"]))
    if case["expect"] == "ok":
        claims = verify_eddsa_token(case["token"], profile, now=now)
        assert claims["aud"] == case["audience"]
        assert claims["token_use"] == case["token_use"]
    else:
        with pytest.raises(JwtVerifyError) as excinfo:
            verify_eddsa_token(case["token"], profile, now=now)
        assert excinfo.value.category == case["expect"]
